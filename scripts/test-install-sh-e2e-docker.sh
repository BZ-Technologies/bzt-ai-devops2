#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
IMAGE_NAME="${OPENBZ_INSTALL_E2E_IMAGE:-${BZDBOT_INSTALL_E2E_IMAGE:-openbz-install-e2e:local}}"
INSTALL_URL="${OPENBZ_INSTALL_URL:-${BZDBOT_INSTALL_URL:-https://openbz.bot/install.sh}}"

OPENAI_API_KEY="${OPENAI_API_KEY:-}"
ANTHROPIC_API_KEY="${ANTHROPIC_API_KEY:-}"
ANTHROPIC_API_TOKEN="${ANTHROPIC_API_TOKEN:-}"
OPENBZ_E2E_MODELS="${OPENBZ_E2E_MODELS:-${BZDBOT_E2E_MODELS:-}}"

echo "==> Build image: $IMAGE_NAME"
docker build \
  -t "$IMAGE_NAME" \
  -f "$ROOT_DIR/scripts/docker/install-sh-e2e/Dockerfile" \
  "$ROOT_DIR/scripts/docker/install-sh-e2e"

echo "==> Run E2E installer test"
docker run --rm \
  -e OPENBZ_INSTALL_URL="$INSTALL_URL" \
  -e OPENBZ_INSTALL_TAG="${OPENBZ_INSTALL_TAG:-${BZDBOT_INSTALL_TAG:-latest}}" \
  -e OPENBZ_E2E_MODELS="$OPENBZ_E2E_MODELS" \
  -e OPENBZ_INSTALL_E2E_PREVIOUS="${OPENBZ_INSTALL_E2E_PREVIOUS:-${BZDBOT_INSTALL_E2E_PREVIOUS:-}}" \
  -e OPENBZ_INSTALL_E2E_SKIP_PREVIOUS="${OPENBZ_INSTALL_E2E_SKIP_PREVIOUS:-${BZDBOT_INSTALL_E2E_SKIP_PREVIOUS:-0}}" \
  -e OPENAI_API_KEY="$OPENAI_API_KEY" \
  -e ANTHROPIC_API_KEY="$ANTHROPIC_API_KEY" \
  -e ANTHROPIC_API_TOKEN="$ANTHROPIC_API_TOKEN" \
  "$IMAGE_NAME"
